// 把 assets/ 里的透明视频内联进 src/client.js，生成可直接加载的 client.js。
// 用法：npm run build
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = readFileSync(join(root, 'src', 'client.js'), 'utf8');

const dataUri = (file) =>
  'data:video/webm;base64,' + readFileSync(join(root, 'assets', file)).toString('base64');

const out = src
  .replace('__VIDEO_IDLE__', dataUri('idle.webm'))
  .replace('__VIDEO_HAPPY__', dataUri('happy.webm'));

if (out.includes('__VIDEO_')) throw new Error('build: unresolved video placeholder');

writeFileSync(
  join(root, 'client.js'),
  '// @generated by scripts/build.mjs — edit src/client.js and run `npm run build`.\n' + out,
);
console.log('client.js built:', Buffer.byteLength(out), 'bytes');
